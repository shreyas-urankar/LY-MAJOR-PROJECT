// PDF Buffer validation helper
const validatePDFBuffer = (buffer) => {
    if (!buffer || buffer.length === 0) {
        throw new Error('Generated PDF buffer is empty');
    }
    if (!Buffer.isBuffer(buffer)) {
        throw new Error('Generated data is not a valid buffer');
    }
    return buffer;
};

// ✅ Generate comprehensive dashboard report
export const generateReport = async (req, res) => {
    try {
        const userId = req.user.id;
        const username = req.user.username;
        const { city = "Pune", year = new Date().getFullYear() } = req.query;

        console.log(`📊 Generating comprehensive dashboard report for ${username} (${city}, ${year})`);

        // Fetch all data for the dashboard report
        let [populationData, infrastructureData, environmentData, transportData, userActions] = await Promise.all([
            Population.find({ city }).sort({ year: -1 }).lean(),
            Infrastructure.find({ city }).sort({ year: -1 }).lean(),
            Environment.find({ userId, city }).sort({ createdAt: -1 }).lean(),
            Transport.find({ city }).sort({ date: -1 }).lean(),
            Data.find({ userId }).sort({ createdAt: -1 }).lean()
        ]);

        if (environmentData.length === 0) {
            environmentData = await Environment.find({ city }).sort({ createdAt: -1 }).lean();
        }

        console.log(`✅ Data fetched: Pop=${populationData.length}, Infra=${infrastructureData.length}, Env=${environmentData.length}, Trans=${transportData.length}`);

        // Calculate dashboard statistics
        const populationStats = calculatePopulationStats(populationData);
        const infrastructureStats = calculateInfrastructureStats(infrastructureData);
        const environmentStats = calculateEnvironmentStats(environmentData);
        const transportStats = calculateTransportStats(transportData);

        // Create PDF
        const doc = new jsPDF();

        // Cover Page
        doc.setFontSize(24);
        doc.setTextColor(40, 53, 147);
        doc.text("URBAN GROWTH DASHBOARD REPORT", 105, 40, { align: 'center' });

        doc.setFontSize(16);
        doc.setTextColor(100, 100, 100);
        doc.text(`${city} Urban Analytics | ${year}`, 105, 60, { align: 'center' });

        doc.setFontSize(12);
        doc.text(`Generated by: ${username}`, 105, 75, { align: 'center' });
        doc.text(new Date().toLocaleDateString(), 105, 85, { align: 'center' });

        doc.setDrawColor(40, 53, 147);
        doc.setLineWidth(2);
        doc.line(20, 95, 190, 95);

        doc.setFontSize(10);
        doc.setTextColor(150, 150, 150);
        doc.text("AI-Powered Urban Growth Dashboard - Comprehensive Analysis", 105, 100, { align: 'center' });

        // Page 2: Executive Summary
        doc.addPage();
        doc.setFontSize(18);
        doc.setTextColor(40, 53, 147);
        doc.text("Executive Summary - Dashboard Overview", 20, 20);

        doc.setFontSize(11);
        doc.setTextColor(0, 0, 0);

        const summaryText = `
This comprehensive dashboard report provides insights into urban growth patterns for ${city}. 
The data represents real-time analytics from the AI Urban Growth Dashboard.

KEY PERFORMANCE INDICATORS (KPIs):
${populationStats ? `• Total Population: ${(populationStats.latestPopulation / 1000000).toFixed(2)} Million` : '• Population data not available'}
${populationStats ? `• Annual Growth Rate: ${populationStats.avgGrowthRate.toFixed(2)}%` : ''}
${infrastructureStats ? `• Smart City Score: ${infrastructureStats.avgSmartScore.toFixed(1)}/100` : '• Infrastructure data not available'}
${environmentStats ? `• Average AQI: ${environmentStats.avgAQI.toFixed(1)}` : '• Environment data not available'}
${transportStats ? `• Traffic Congestion: ${transportStats.avgCongestion.toFixed(1)}%` : '• Transport data not available'}

DASHBOARD HIGHLIGHTS:
1. POPULATION: ${populationStats ? populationStats.growthTrend : 'No data available'}
2. INFRASTRUCTURE: ${infrastructureStats ? infrastructureStats.trend : 'No data available'}
3. ENVIRONMENT: ${environmentStats ? getPollutionText(environmentStats.pollutionLevel) : 'No data available'}
4. TRANSPORT: ${transportStats ? transportStats.efficiency : 'No data available'}

DATA SOURCES:
• Population: ${populationData.length} records
• Infrastructure: ${infrastructureData.length} records  
• Environment: ${environmentData.length} records
• Transport: ${transportData.length} records
• User Activity: ${userActions.length} actions

${generateDashboardRecommendations(populationStats, infrastructureStats, environmentStats, transportStats)}
    `.trim();

        doc.text(summaryText, 20, 35, { maxWidth: 170 });

        // Add module pages
        if (populationData.length > 0) addPopulationPage(doc, populationData, populationStats);
        if (infrastructureData.length > 0) addInfrastructurePage(doc, infrastructureData, infrastructureStats);
        if (environmentData.length > 0) addEnvironmentPage(doc, environmentData, environmentStats);
        if (transportData.length > 0) addTransportPage(doc, transportData, transportStats);

        // Footer on all pages
        const pageCount = doc.internal.getNumberOfPages();
        for (let i = 1; i <= pageCount; i++) {
            doc.setPage(i);
            doc.setFontSize(8);
            doc.setTextColor(150, 150, 150);
            doc.text(`Page ${i} of ${pageCount}`, 105, 285, { align: 'center' });
            doc.text(`Report ID: ${city.toUpperCase()}-${Date.now().toString().slice(-8)}`, 105, 290, { align: 'center' });
        }

        // Convert to buffer and send
        const pdfBuffer = Buffer.from(doc.output('arraybuffer'));
        validatePDFBuffer(pdfBuffer);

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename=${city}_comprehensive_report_${Date.now()}.pdf`);
        res.setHeader('Content-Length', pdfBuffer.length);
        res.setHeader('Access-Control-Expose-Headers', 'Content-Disposition');

        res.send(pdfBuffer);

        console.log(`✅ Report generated successfully: ${pdfBuffer.length} bytes`);

        // Log async
        Data.create({
            userId, username,
            action: "DASHBOARD_REPORT_GENERATED",
            analysisResult: `Comprehensive dashboard report generated for ${city}`,
            city,
        }).catch(err => console.error("Error logging report:", err));

    } catch (error) {
        console.error("❌ Report Generation Error:", error);
        res.status(500).json({
            success: false,
            message: "Error generating dashboard report",
            error: error.message,
            stack: process.env.NODE_ENV === 'development' ? error.stack : undefined
        });
    }
};

export const generateModuleDashboardReport = async (req, res) => {
    const { module } = req.params;
    try {
        const userId = req.user.id;
        const username = req.user.username;
        const city = req.query.city || "Pune";

        console.log(`📊 Generating ${module} dashboard report for ${username}`);

        const doc = new jsPDF();

        // Header
        doc.setFontSize(20);
        doc.setTextColor(40, 53, 147);
        doc.text(`${module.charAt(0).toUpperCase() + module.slice(1)} Dashboard Report`, 105, 20, { align: 'center' });

        doc.setFontSize(12);
        doc.setTextColor(100, 100, 100);
        doc.text(`${city} Urban Analytics | ${new Date().toLocaleDateString()}`, 105, 30, { align: 'center' });
        doc.text(`Generated by: ${username}`, 105, 40, { align: 'center' });

        // Add module-specific content
        switch (module.toLowerCase()) {
            case 'population':
                const popData = await Population.find({ city }).sort({ year: -1 }).lean();
                const popStats = calculatePopulationStats(popData);
                addPopulationDashboard(doc, popData, popStats);
                break;
            case 'infrastructure':
                const infraData = await Infrastructure.find({ city }).sort({ year: -1 }).lean();
                const infraStats = calculateInfrastructureStats(infraData);
                addInfrastructureDashboard(doc, infraData, infraStats);
                break;
            case 'environment':
                let envData = await Environment.find({ userId, city }).sort({ createdAt: -1 }).lean();
                if (envData.length === 0) {
                    envData = await Environment.find({ city }).sort({ createdAt: -1 }).lean();
                }
                const envStats = calculateEnvironmentStats(envData);
                addEnvironmentDashboard(doc, envData, envStats);
                break;
            case 'transport':
                const transData = await Transport.find({ city }).sort({ date: -1 }).lean();
                const transStats = calculateTransportStats(transData);
                addTransportDashboard(doc, transData, transStats);
                break;
            default:
                throw new Error(`Unknown module: ${module}`);
        }

        // Footer
        const pageCount = doc.internal.getNumberOfPages();
        for (let i = 1; i <= pageCount; i++) {
            doc.setPage(i);
            doc.setFontSize(8);
            doc.setTextColor(150, 150, 150);
            doc.text(`${module.toUpperCase()} Report - Page ${i} of ${pageCount}`, 105, 285, { align: 'center' });
        }

        const pdfBuffer = Buffer.from(doc.output('arraybuffer'));
        validatePDFBuffer(pdfBuffer);

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename=${module}_report_${city}_${Date.now()}.pdf`);
        res.setHeader('Content-Length', pdfBuffer.length);
        res.setHeader('Access-Control-Expose-Headers', 'Content-Disposition');

        res.send(pdfBuffer);

        console.log(`✅ ${module} report generated: ${pdfBuffer.length} bytes`);

        Data.create({
            userId, username,
            action: "MODULE_DASHBOARD_REPORT",
            analysisResult: `${module} dashboard report generated`,
            city,
        }).catch(err => console.error("Error logging:", err));

    } catch (error) {
        console.error(`❌ ${module} Report Error:`, error);
        res.status(500).json({
            success: false,
            message: `Error generating ${module} dashboard report`,
            error: error.message
        });
    }
};

