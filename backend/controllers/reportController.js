// Calculation functions
function calculatePopulationStats(populationData) {
    if (!populationData || populationData.length === 0) return null;

    const latest = populationData[0];
    const earliest = populationData[populationData.length - 1];

    const totalGrowth = latest.totalPopulation - earliest.totalPopulation;
    const growthPercentage = (totalGrowth / earliest.totalPopulation * 100).toFixed(2);
    const avgGrowthRate = populationData.reduce((sum, item) => sum + item.growthRate, 0) / populationData.length;
    const avgDensity = populationData.reduce((sum, item) => sum + item.density, 0) / populationData.length;

    return {
        latestPopulation: latest.totalPopulation,
        avgGrowthRate,
        avgDensity,
        growthTrend: avgGrowthRate > 2.5 ? 'Rapid Growth ↗' : avgGrowthRate > 1.5 ? 'Moderate Growth →' : 'Stable ↘',
        yearRange: { start: earliest.year, end: latest.year },
        totalGrowth,
        growthPercentage
    };
}

function calculateInfrastructureStats(infrastructureData) {
    if (!infrastructureData || infrastructureData.length === 0) return null;

    const latest = infrastructureData[0];
    const avgSmartScore = infrastructureData.reduce((sum, item) => sum + item.smartCityScore, 0) / infrastructureData.length;

    const roadsScore = Math.min(100, (latest.roadsKm / 1000) * 100);
    const healthScore = Math.min(100, (latest.hospitals / 100) * 100);
    const educationScore = Math.min(100, (latest.schools / 500) * 100);
    const housingScore = latest.housingIndex || 65;

    const overallScore = (roadsScore * 0.2 + healthScore * 0.2 + educationScore * 0.2 + housingScore * 0.2 + latest.smartCityScore * 0.2);

    return {
        roadsScore, healthScore, educationScore, housingScore,
        smartCityScore: latest.smartCityScore,
        avgSmartScore,
        overallScore,
        trend: latest.smartCityScore > 75 ? 'Improving ↗' : latest.smartCityScore > 60 ? 'Stable →' : 'Needs Attention ↘'
    };
}

function calculateEnvironmentStats(environmentData) {
    if (!environmentData || environmentData.length === 0) return null;

    const latest = environmentData[0];
    const avgAQI = environmentData.reduce((sum, item) => sum + (item.aqi || 0), 0) / environmentData.length;
    const avgPM25 = environmentData.reduce((sum, item) => sum + (item.pm25 || 0), 0) / environmentData.length;
    const avgGreenCover = environmentData.reduce((sum, item) => sum + (item.greenCover || 0), 0) / environmentData.length;

    return {
        avgAQI, avgPM25, avgGreenCover,
        pollutionLevel: latest.pollutionLevel || 'Moderate',
        lastUpdated: latest.createdAt,
        dataPoints: environmentData.length
    };
}

function calculateTransportStats(transportData) {
    if (!transportData || transportData.length === 0) return null;

    const avgCongestion = transportData.reduce((sum, item) => sum + (item.congestionLevel || 0), 0) / transportData.length;
    const avgSpeed = transportData.reduce((sum, item) => sum + (item.avgSpeed || 0), 0) / transportData.length;
    const avgTrafficIndex = transportData.reduce((sum, item) => sum + (item.trafficIndex || 0), 0) / transportData.length;

    return {
        avgCongestion, avgSpeed, avgTrafficIndex,
        peakHours: '8-10 AM, 5-7 PM',
        weeklyPattern: 'Heavier on weekdays',
        efficiency: avgSpeed > 40 ? 'Good Flow ✅' : avgSpeed > 25 ? 'Moderate ⚠️' : 'Poor 🚫'
    };
}

// Utility functions
function getTrendIcon(growthRate) {
    if (growthRate > 2.5) return '↗ Rapid Growth';
    if (growthRate > 1.5) return '→ Moderate Growth';
    return '↘ Stable';
}

function getAQIStatus(aqi) {
    if (!aqi) return 'N/A';
    if (aqi <= 50) return 'Good ✅';
    if (aqi <= 100) return 'Moderate ⚠️';
    if (aqi <= 150) return 'Unhealthy ❗';
    return 'Hazardous ☠️';
}

function getPM25Status(pm25) {
    if (!pm25) return 'N/A';
    if (pm25 <= 12) return 'Good';
    if (pm25 <= 35) return 'Moderate';
    return 'Unhealthy';
}

function getGreenCoverStatus(cover) {
    if (!cover) return 'N/A';
    if (cover > 30) return 'Excellent';
    if (cover > 20) return 'Good';
    return 'Moderate';
}

function getCongestionStatus(congestion) {
    if (!congestion) return 'N/A';
    if (congestion <= 30) return 'Light ✅';
    if (congestion <= 50) return 'Moderate ⚠️';
    return 'Heavy ❗';
}

function getPollutionText(level) {
    switch (level) {
        case 'Good': return 'Good air quality';
        case 'Moderate': return 'Moderate pollution levels';
        case 'Unhealthy': return 'Elevated pollution';
        default: return 'Moderate conditions';
    }
}

function generateDashboardRecommendations(popStats, infraStats, envStats, transStats) {
    const recommendations = [];

    if (popStats && popStats.avgGrowthRate > 2.5) {
        recommendations.push('• Accelerate infrastructure development');
    }
    if (infraStats && infraStats.overallScore < 70) {
        recommendations.push('• Increase smart city investment');
    }
    if (envStats && envStats.avgAQI > 100) {
        recommendations.push('• Implement pollution control measures');
    }
    if (transStats && transStats.avgCongestion > 60) {
        recommendations.push('• Enhance public transportation');
    }

    if (recommendations.length === 0) {
        recommendations.push('• Continue current strategies');
    }

    return '\nRECOMMENDATIONS:\n' + recommendations.join('\n');
}

